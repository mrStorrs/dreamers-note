#!/usr/bin/env node

import fs from "node:fs";
import os from "node:os";
import path from "node:path";

const marker = "<!-- dreamers-note: generated path index -->";

try {
  const [vaultPath, ...extra] = process.argv.slice(2);
  if (!vaultPath || !path.isAbsolute(vaultPath) || extra.length) {
    throw new Error("usage: node scripts/build-note-index.mjs <absolute-vault-path>");
  }
  const vault = path.resolve(vaultPath);
  if (vault === path.parse(vault).root || vault === os.homedir()) {
    throw new Error("select a vault directory, not the filesystem root or home directory");
  }
  if (!fs.lstatSync(vault).isDirectory()) throw new Error("vault must be a directory, not a symlink");
  const target = path.join(vault, "note-index.md");
  let previous;
  const existing = fs.lstatSync(target, { throwIfNoEntry: false });
  if (existing) {
    if (!existing.isFile()) throw new Error("note-index.md must be a regular file, not a symlink");
    previous = fs.readFileSync(target, "utf8");
    if (!previous.startsWith(marker + "\n")) {
      throw new Error("note-index.md is not generated by this script; preserve it and choose its destination explicitly");
    }
  }

  const notes = [];
  walk(vault, "");
  notes.sort();
  const lines = [marker, "# Note index", "", "Generated from note paths. Read the linked notes for their content.", ""];
  for (const note of notes) {
    const label = note.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;")
      .replace(/[\\[\]\x60*_]/g, "\\$&");
    const href = note.split("/").map(part => encodeURIComponent(part)
      .replace(/[!'()*]/g, char => "%" + char.charCodeAt(0).toString(16).toUpperCase())).join("/");
    lines.push("- [" + label + "](./" + href + ")");
  }
  const content = lines.join("\n") + "\n";
  if (content !== previous) {
    const staging = fs.mkdtempSync(path.join(vault, ".note-index-"));
    const temporary = path.join(staging, "note-index.md");
    try {
      fs.writeFileSync(temporary, content, { encoding: "utf8", mode: 0o600 });
      fs.renameSync(temporary, target);
    } finally {
      if (fs.existsSync(temporary)) fs.unlinkSync(temporary);
      fs.rmdirSync(staging);
    }
  }
  console.log("note-index.md: " + notes.length + " notes" + (content === previous ? " (unchanged)" : ""));

  function walk(directory, relative) {
    for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
      if (entry.name.startsWith(".") || entry.isSymbolicLink() || /[\x00-\x1f\x7f]/.test(entry.name)) continue;
      const note = relative ? relative + "/" + entry.name : entry.name;
      if (note.toLowerCase() === "07-system/secrets" || note === "note-index.md") continue;
      const absolute = path.join(directory, entry.name);
      if (entry.isDirectory()) walk(absolute, note);
      else if (entry.isFile() && /\.md$/i.test(entry.name)) notes.push(note);
    }
  }
} catch (error) {
  console.error("index failed: " + error.message);
  process.exitCode = 1;
}
